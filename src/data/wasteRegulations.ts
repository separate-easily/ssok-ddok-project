// 프롬프트 생성용 함수 - 조례 데이터를 텍스트로 변환
export const getRegulationsContext = (): string => {
  const { categories, faq, coreRules, cityInfo, collectionSchedule } = wasteRegulations;

  let context = `## ${cityInfo.name} 폐기물 관리 조례 기반 분리수거 가이드\n\n`;

  context += `### 수거 일정\n`;
  context += `- 재활용품: ${collectionSchedule.recyclables}\n`;
  context += `- 음식물쓰레기: ${collectionSchedule.foodWaste}\n`;
  context += `- 일반쓰레기: ${collectionSchedule.generalWaste}\n`;
  context += `- 대형폐기물: ${collectionSchedule.bulkyWaste}\n\n`;

  context += `### 핵심 원칙\n`;
  coreRules.forEach((rule, i) => {
    context += `${i + 1}. ${rule}\n`;
  });
  context += `\n`;

  context += `### 분리수거 카테고리별 안내\n\n`;

  Object.entries(categories).forEach(([key, cat]) => {
    context += `#### ${cat.name}\n`;
    context += `배출 장소: ${cat.binColor}\n`;
    context += `배출 가능: ${cat.items.slice(0, 5).join(", ")} 등\n`;
    context += `배출 방법: ${cat.howTo.slice(0, 2).join("; ")}\n`;
    context += `배출 불가: ${cat.notAllowed.slice(0, 3).join(", ")}\n\n`;
  });

  context += `### 자주 묻는 질문\n`;
  faq.forEach((item) => {
    context += `Q: ${item.question}\nA: ${item.answer}\n\n`;
  });

  context += `### 문의처\n`;
  context += `- 평택시 콜센터: ${cityInfo.wasteHotline}\n`;
  context += `- 홈페이지: ${cityInfo.websiteUrl}\n`;

  return context;
};

export default wasteRegulations;
